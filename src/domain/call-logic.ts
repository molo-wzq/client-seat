/** 提示词用的一段式文本:每条规律一行(规律+用法)。 */
export function formatCallLogicForPrompt(): string {
  return CALL_LOGIC_LAWS.map(
    (law, index) => `${index + 1}. ${law.name}:${law.law}电话里:${law.usage}`,
  ).join("\n");
}
